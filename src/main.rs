mod build;
mod cli;
mod fetch;
mod manifest;
mod paths;
mod profile;

use anyhow::Result;
use clap::Parser;
use cli::{Cli, Cmd};
use manifest::Manifest;
use paths::Paths;
use profile::Profile;
use std::path::{Path, PathBuf};

fn main() -> Result<()> {
    // Define version constants from Cargo metadata
    const HANGAR_MAJOR: &str = env!("CARGO_PKG_VERSION_MAJOR");
    const HANGAR_MINOR: &str = env!("CARGO_PKG_VERSION_MINOR");
    const HANGAR_MICRO: &str = env!("CARGO_PKG_VERSION_PATCH");

    // Print the version banner when Hangar executes
    println!("hangar {}.{}.{}", HANGAR_MAJOR, HANGAR_MINOR, HANGAR_MICRO);

    match Cli::parse().cmd {
        Cmd::Install { manifest, profile, cmake_out } => {
            install(&manifest, &profile, cmake_out.as_deref())
        }
    }
}

/// CMake wants forward slashes, even on Windows.
fn fwd(p: &Path) -> String {
    p.to_string_lossy().replace('\\', "/")
}

fn install(
    manifest_path: &Path,
    profile_path: &Path,
    cmake_out: Option<&Path>,
) -> Result<()> {
    let manifest = Manifest::load(manifest_path)?;
    let profile = Profile::load(profile_path)?;
    let paths = Paths::new(&profile);

    println!("Project  : {} v{}", manifest.package.name, manifest.package.version);
    println!("Profile  : {} ({})", profile.name, profile.key());
    println!("Root     : {}", paths.root.display());
    println!();
    println!("Plan ({} dependencies):", manifest.dependencies.len());

    for (name, dep) in &manifest.dependencies {
        let kind = if dep.headers.is_empty() { "compiled" } else { "header-only" };
        println!("  - {name} @ {} ({kind})", dep.tag);
    }
    println!();

    let mut installed: Vec<PathBuf> = Vec::new();

    for (name, dep) in &manifest.dependencies {
        let source_dir = paths.source(name, &dep.tag);
        let commit = fetch::fetch(name, dep, &source_dir)?;
        let built = build::build(name, dep, &profile, &paths, &source_dir, &commit, &installed)?;

        installed.push(paths.export(name, &dep.tag));
        println!(
            "[hangar] {name}: {} ({})",
            &commit[..10],
            if built { "installed" } else { "already installed" }
        );
    }

    if let Some(out) = cmake_out {
        let mut text = String::from("# Generated by hangar, do not edit\n");
        for (name, dep) in &manifest.dependencies {
            let prefix = fwd(&paths.export(name, &dep.tag));
            if dep.headers.is_empty() {
                // Compiled library: find_package() finds its config file here
                text += &format!("list(APPEND CMAKE_PREFIX_PATH \"{prefix}\")\n");
            } else {
                // Header-only library: an imported target that carries the include path
                text += &format!(
                    "add_library(hangar::{name} INTERFACE IMPORTED GLOBAL)\n\
                     set_target_properties(hangar::{name} PROPERTIES \
                     INTERFACE_INCLUDE_DIRECTORIES \"{prefix}/include\")\n"
                );
            }
        }
        std::fs::write(out, text)?;
        println!("Wrote {}", out.display());
    }

    println!();
    println!("Done.");
    Ok(())
}